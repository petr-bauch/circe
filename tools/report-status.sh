#!/usr/bin/env bash
# Regenerate docs/report/generated/status.tex from workspace truth.
# Read-only w.r.t. tracked files: writes only the gitignored generated output.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
OUT="$ROOT/docs/report/generated/status.tex"
mkdir -p "$(dirname "$OUT")"

SHA="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
DATE="$(date -u +%Y-%m-%d)"
TOOLCHAIN="$(tr -d '[:space:]' < "$ROOT/lean-toolchain" 2>/dev/null || echo unknown)"
TOTAL="$(find "$ROOT/Circe" -name '*.lean' | wc -l | tr -d ' ')"

row() {
  # $1 = label, $2 = path relative to ROOT
  local label="$1" rel="$2" files loc
  files="$(find "$ROOT/$rel" -maxdepth 4 -name '*.lean' 2>/dev/null | wc -l | tr -d ' ')"
  loc="$(find "$ROOT/$rel" -maxdepth 4 -name '*.lean' 2>/dev/null -exec cat {} + 2>/dev/null | wc -l | tr -d ' ')"
  printf '\\texttt{%s} & %s & %s \\\\\n' "$label" "$files" "$loc"
}

{
  echo "% Auto-generated by tools/report-status.sh — do not edit by hand."
  echo "% Source of truth: Circe/**/*.lean, lean-toolchain, git HEAD."
  echo "\\renewcommand{\\circegitsha}{$SHA}"
  echo "\\renewcommand{\\circemodulecount}{$TOTAL}"
  echo "\\renewcommand{\\circeleancount}{$TOTAL}"
  echo ""
  echo "\\begin{center}"
  echo "\\begin{tabular}{lrr}"
  echo "\\toprule"
  echo "Area \\& files \\& lines \\\\"
  echo "\\midrule"
  row "Base" "Circe/Base.lean"
  row "CoreIR" "Circe/CoreIR.lean"
  row "Eval" "Circe/Eval"
  row "Mem" "Circe/Mem"
  row "Transfer" "Circe/Transfer"
  row "Emit" "Circe/Emit"
  row "Validator" "Circe/Validator.lean"
  row "Specs" "Circe/Specs.lean"
  echo "\\bottomrule"
  echo "\\end{tabular}"
  echo "\\end{center}"
  echo ""
  echo "\\begin{quote}"
  echo "Snapshot $DATE, git \\texttt{$SHA}, toolchain \\texttt{$TOOLCHAIN},"
  echo "total Lean modules under \\texttt{Circe/}: $TOTAL."
  echo "\\end{quote}"
} > "$OUT"

echo "wrote $OUT (sha=$SHA, modules=$TOTAL)"
